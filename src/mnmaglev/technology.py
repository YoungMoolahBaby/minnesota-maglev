"""The technology comparison: run the same corridors, stations and demand model as maglev, dedicated
high-speed rail or upgraded conventional rail (params/technology.yaml, `mnmaglev compare`)."""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path


from .network import Line
from .params import TECHNOLOGIES, Param, apply_technology


def technology_lines(lines: list[Line], params: dict[str, Param], tech: str) -> list[Line]:
    """Dedicated HSR can run at grade on embankment where the maglev beam is elevated (snow, the
    beam's own clearance): move technology.hsr.elevated_to_at_grade of the rural elevated km to at
    grade, and scale the tall piers down with them. Other technologies keep the lines as they are."""
    if tech != "hsr":
        return lines
    share = params["technology.hsr.elevated_to_at_grade"].value
    out = []
    for line in lines:
        segs = []
        for s in line.segments:
            st = dict(s.structure)
            moved = st.get("elevated", 0.0) * share
            st["elevated"] = st.get("elevated", 0.0) - moved
            st["at_grade"] = st.get("at_grade", 0.0) + moved
            piers = {h: v * (1 - share) for h, v in s.pier_excess.items()}
            segs.append(replace(s, structure=st, pier_excess=piers))
        out.append(replace(line, segments=segs))
    return out


def prepare(params: dict[str, Param], lines: list[Line], tech: str) -> tuple[dict[str, Param], list[Line]]:
    p = apply_technology(params, tech)
    return p, technology_lines(lines, params, tech)


def compare_markdown(runs: dict[str, dict]) -> str:
    """One table per question: what it costs, how fast it is, who rides, and whether it pays."""
    from .report import _bn, _hm

    L = ["# Technology comparison: same corridors, stations and demand model\n",
         "Generated by `mnmaglev compare`. Each technology runs the whole model (costs with cost growth, "
         "kinematics or schedule speed, ridership, USDOT benefit-cost) with its overrides from "
         "params/technology.yaml. Capital is the lines' (transport only, fusion excluded), expected value "
         "(mean) and P50, 2026 USD.\n"]
    phases = sorted(next(iter(runs.values()))["demand"]["phases"])
    L.append("| Technology | " + " | ".join(f"Through phase {p}: capital mean (P50)" for p in phases) + " |")
    L.append("|---|" + "---|" * len(phases))
    for t, net in runs.items():
        cells = []
        for ph in phases:
            x = net["demand"]["phases"][ph]
            cells.append(f"{_bn(x['capital_mean'])} ({_bn(x['capital_p50'])})")
        L.append(f"| {t} | " + " | ".join(cells) + " |")
    L.append("\nTravel times (station to station, incl. changes):\n")
    pairs = [("twin_cities", "duluth"), ("twin_cities", "rochester"), ("twin_cities", "st_cloud"),
             ("twin_cities", "fargo"), ("twin_cities", "chicago"), ("twin_cities", "des_moines"),
             ("twin_cities", "denver"), ("chicago", "denver")]
    L.append("| Technology | " + " | ".join(f"{a.replace('twin_cities', 'Twin Cities')} - {b}" for a, b in pairs) + " |")
    L.append("|---|" + "---|" * len(pairs))
    last = phases[-1]
    for t, net in runs.items():
        res = net["demand"]["phases"][last]["res"]
        by = {frozenset((p["a"], p["b"])): p for p in res["pairs"]}
        cells = [_hm(by[frozenset(ab)]["minutes"] * 60) if frozenset(ab) in by else "-" for ab in pairs]
        L.append(f"| {t} | " + " | ".join(cells) + " |")
    L.append("\nRidership and benefit-cost (forecast year, most likely values; BCR on the expected capital):\n")
    L.append("| Technology | Through phase | Riders / yr | Fares / yr | O&M P50 / yr | Farebox | Benefits / yr "
             "| BCR at 7% | BCR at 3.1% | Break-even capital per route-km at 7% |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for t, net in runs.items():
        for ph in phases:
            x = net["demand"]["phases"][ph]
            b, bc = x["benefits"], x["bcr"]
            km = sum(r["line"].length_km for r in net["results"] if r["line"].phase <= ph)
            # capital at which PV benefits + residual = PV capital + O&M (both scale linearly with capital)
            k_cap = bc["pv_capital"] / x["capital_mean"]
            k_res = bc["pv_residual"] / x["capital_mean"]
            breakeven = (bc["pv_benefits"] - bc["pv_om"]) / (k_cap - k_res) if k_cap > k_res else float("nan")
            L.append(f"| {t} | {ph} | {b['riders'] / 1e6:,.1f} M | ${b['revenue_musd']:,.0f} M | ${x['opex']:,.0f} M "
                     f"| {b['revenue_musd'] / x['opex']:.0%} | ${b['total_musd']:,.0f} M | **{bc['bcr']:.3f}** "
                     f"| {x['bcr_alt']['bcr']:.3f} | ${max(breakeven, 0) / km:,.0f} M |")
    L.append("\nCaveats. HSR runs on the maglev's alignments, which climb up to 10% grades and curve to the "
             "maglev's radius; a wheel-rail line (2.5-3.5%, ~5.5 km radius at 320 km/h) would need longer "
             "approaches (Duluth) and some re-routing, so HSR's cost and time here are a little optimistic. "
             "The energy model has no rolling resistance and maglev drag, so HSR energy (~12 kWh per train-km "
             "vs CA HSR's ~23) and its O&M are understated slightly. Upgraded rail is a sketch: an all-in cost "
             "per km of our route and the schedule speed real Midwest services deliver on freight track, at 4 "
             "round trips a day; its on-time performance (Borealis ~57% in FY2025, as reported by an advocacy "
             "group) isn't in the demand model. All three keep the robot patrols; the maglev's premium "
             "constant (California HSR's, halved) applies to HSR too, none to upgraded rail.\n")
    return "\n".join(L) + "\n"


def run_all(params, lines, n: int, seed: int, out: Path, **settings) -> Path:
    from .report import run_network

    runs = {}
    for tech in TECHNOLOGIES:
        p, ls = prepare(params, lines, tech)
        print(f"running {tech} ...", flush=True)
        runs[tech] = run_network(ls, p, n=n, seed=seed, **settings)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "compare.md"
    path.write_text(compare_markdown(runs), encoding="utf-8")
    return path
